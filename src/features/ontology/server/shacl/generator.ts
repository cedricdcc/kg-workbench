import type { BuildShaclShapesInput } from "./types"
import { normalizeOwlBaseIri } from "@/features/ontology/utils/owl-base-iri"
import { importOntologyToSnapshot } from "../linkml/ast-mapper"
import { compileSnapshotArtifacts } from "../linkml/compiler"

function normalizeDatatype(dataType?: string): string {
  if (!dataType) return "xsd:string"
  const lower = dataType.toLowerCase().trim()
  if (lower.startsWith("xsd:")) return dataType
  if (lower === "integer" || lower === "int") return "xsd:integer"
  if (
    lower === "number" ||
    lower === "float" ||
    lower === "double" ||
    lower === "decimal"
  )
    return "xsd:float"
  if (lower === "boolean" || lower === "bool") return "xsd:boolean"
  if (lower === "date") return "xsd:date"
  if (lower === "datetime") return "xsd:dateTime"
  return "xsd:string"
}

function escapeTurtleString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')
}

function sanitizeIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_-]/g, "_")
}

export function buildLegacyShaclShapes({
  baseIri,
  ontology,
  closed = false,
}: BuildShaclShapesInput): string {
  const normalizedBase = normalizeOwlBaseIri(baseIri).replace(/[#/]+$/, "")
  const classes = ontology.classes ?? []
  const relations = ontology.relations ?? []

  const classNameMap = new Map(
    classes.map((c) => [c.id ?? c.name, sanitizeIdentifier(c.name)])
  )

  const lines: string[] = [
    `# W3C SHACL Shapes generated by KG Workbench`,
    `# Ontology: ${ontology.name}`,
    ``,
    `@prefix sh: <http://www.w3.org/ns/shacl#> .`,
    `@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .`,
    `@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .`,
    `@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .`,
    `@prefix ont: <${normalizedBase}#> .`,
    ``,
  ]

  for (const cls of classes) {
    const classId = cls.id ?? cls.name
    const className = sanitizeIdentifier(cls.name)
    const classShapeIri = `ont:${className}Shape`
    const classTargetIri = `ont:${className}`

    lines.push(`${classShapeIri}`)
    lines.push(`    a sh:NodeShape ;`)
    lines.push(`    sh:targetClass ${classTargetIri} ;`)
    lines.push(`    rdfs:label "${escapeTurtleString(cls.name)} Shape" ;`)
    if (cls.description) {
      lines.push(`    rdfs:comment "${escapeTurtleString(cls.description)}" ;`)
    }
    if (closed) {
      lines.push(`    sh:closed true ;`)
    }

    // Property Shapes for Attributes
    const attributes = cls.attributes ?? []
    for (const attr of attributes) {
      const attrName = sanitizeIdentifier(attr.name)
      const xsdType = normalizeDatatype(attr.dataType)
      lines.push(`    sh:property [`)
      lines.push(`        sh:path ont:${attrName} ;`)
      lines.push(`        sh:datatype ${xsdType} ;`)
      if (attr.required) {
        lines.push(`        sh:minCount 1 ;`)
      }
      lines.push(`        sh:name "${escapeTurtleString(attr.name)}" ;`)
      if (attr.description) {
        lines.push(
          `        sh:description "${escapeTurtleString(attr.description)}" ;`
        )
      }
      lines.push(`    ] ;`)
    }

    // Property Shapes for Domain Relations
    const domainRelations = relations.filter(
      (r) => r.domainClassId === classId || r.domainClassId === cls.name
    )

    for (const rel of domainRelations) {
      const relName = sanitizeIdentifier(rel.name)
      const targetClassIdentifier =
        classNameMap.get(rel.rangeClassId) ??
        sanitizeIdentifier(rel.rangeClassId)

      let minCount: number | null = null
      let maxCount: number | null = null

      if (rel.cardinality === "1:1") {
        minCount = 1
        maxCount = 1
      } else if (rel.cardinality === "1:N") {
        minCount = 1
      } else if (rel.cardinality === "N:1") {
        maxCount = 1
      }

      lines.push(`    sh:property [`)
      lines.push(`        sh:path ont:${relName} ;`)
      lines.push(`        sh:class ont:${targetClassIdentifier} ;`)
      if (minCount !== null) {
        lines.push(`        sh:minCount ${minCount} ;`)
      }
      if (maxCount !== null) {
        lines.push(`        sh:maxCount ${maxCount} ;`)
      }
      lines.push(`        sh:name "${escapeTurtleString(rel.name)}" ;`)
      if (rel.description) {
        lines.push(
          `        sh:description "${escapeTurtleString(rel.description)}" ;`
        )
      }
      lines.push(`    ] ;`)
    }

    // Close the NodeShape definition with a period
    // Replace the trailing semicolon of the last property with a period
    if (lines[lines.length - 1].endsWith(" ;")) {
      lines[lines.length - 1] = lines[lines.length - 1].slice(0, -2) + " ."
    } else {
      lines.push(`    .`)
    }
    lines.push(``)
  }

  return lines.join("\n")
}

export function buildShaclShapes(input: BuildShaclShapesInput): string {
  const { baseIri, ontology, closed = false, preferLinkml, engine } = input

  const isLooseInput =
    !ontology.modules ||
    ontology.modules.length === 0 ||
    ontology.classes?.some((c) => c.id && c.id !== c.name && !c.moduleId)

  const shouldTryLinkml =
    engine === "linkml" ||
    preferLinkml === true ||
    (engine !== "legacy" && preferLinkml !== false && !isLooseInput)

  if (shouldTryLinkml) {
    try {
      const snapshot = importOntologyToSnapshot(ontology, baseIri)
      const { artifacts } = compileSnapshotArtifacts(snapshot, {
        shaclOptions: { closed },
      })
      if (artifacts.shacl_ttl && artifacts.shacl_ttl.trim()) {
        return artifacts.shacl_ttl
      }
    } catch {
      // Fallback to legacy string builder below
    }
  }

  return buildLegacyShaclShapes({ baseIri, ontology, closed })
}
