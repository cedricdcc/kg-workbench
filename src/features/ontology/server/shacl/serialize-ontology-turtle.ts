function sanitizeIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_-]/g, "_")
}

function escapeTurtleLiteral(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')
}

export interface SerializeOntologyInput {
  name?: string
  baseIri?: string
  classes?: Array<{
    id: string
    name: string
    parentClassId?: string | null
    description?: string | null
  }>
  relations?: Array<{
    id: string
    name: string
    sourceClassId: string
    targetClassId: string
  }>
  attributes?: Array<{
    id: string
    classId: string
    name: string
    dataType?: string
    isRequired?: boolean
  }>
  disjointness?: Array<{
    classId: string
    disjointClassId: string
  }>
  examples?: Array<{
    id?: string
    classId: string
    value: string
  }>
}

export function serializeOntologyTurtle(ontology: SerializeOntologyInput): string {
  const base = ontology.baseIri?.replace(/[#/]+$/, "") || "http://example.org/onto"
  const classes = ontology.classes ?? []
  const relations = ontology.relations ?? []
  const disjointness = ontology.disjointness ?? []
  const examples = ontology.examples ?? []

  const classIdToName = new Map<string, string>()
  for (const c of classes) {
    classIdToName.set(c.id, sanitizeIdentifier(c.name))
  }

  const lines: string[] = [
    `# RDF Ontology Data Graph generated by KG Workbench`,
    `@prefix owl: <http://www.w3.org/2002/07/owl#> .`,
    `@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .`,
    `@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .`,
    `@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .`,
    `@prefix : <${base}#> .`,
    ``,
    `<${base}> a owl:Ontology ;`,
    `    rdfs:label "${escapeTurtleLiteral(ontology.name || "Ontology")}" .`,
    ``,
  ]

  // Classes
  for (const c of classes) {
    const className = classIdToName.get(c.id)!
    lines.push(`:${className} a owl:Class ;`)
    lines.push(`    rdfs:label "${escapeTurtleLiteral(c.name)}" ;`)

    if (c.parentClassId && classIdToName.has(c.parentClassId)) {
      const parentName = classIdToName.get(c.parentClassId)!
      lines.push(`    rdfs:subClassOf :${parentName} ;`)
    }

    lines.push(`    rdfs:isDefinedBy <${base}> .`)
    lines.push(``)
  }

  // Disjointness
  for (const d of disjointness) {
    const c1 = classIdToName.get(d.classId)
    const c2 = classIdToName.get(d.disjointClassId)
    if (c1 && c2 && c1 !== c2) {
      lines.push(`:${c1} owl:disjointWith :${c2} .`)
    }
  }
  if (disjointness.length > 0) {
    lines.push(``)
  }

  // Relations (Object Properties)
  for (const r of relations) {
    const relName = sanitizeIdentifier(r.name)
    const sourceClass = classIdToName.get(r.sourceClassId)
    const targetClass = classIdToName.get(r.targetClassId)

    lines.push(`:${relName} a owl:ObjectProperty ;`)
    lines.push(`    rdfs:label "${escapeTurtleLiteral(r.name)}" ;`)
    if (sourceClass) {
      lines.push(`    rdfs:domain :${sourceClass} ;`)
    }
    if (targetClass) {
      lines.push(`    rdfs:range :${targetClass} ;`)
    }
    lines.push(`    rdfs:isDefinedBy <${base}> .`)
    lines.push(``)
  }

  // Class Instances / Examples
  let exampleIdx = 0
  for (const ex of examples) {
    const targetClass = classIdToName.get(ex.classId)
    if (targetClass) {
      exampleIdx++
      const instanceId = `inst_${exampleIdx}`
      lines.push(`:${instanceId} a :${targetClass} ;`)
      lines.push(`    rdfs:label "${escapeTurtleLiteral(ex.value)}" .`)
      lines.push(``)
    }
  }

  return lines.join("\n")
}
